import {readFileSync,writeFileSync,mkdirSync,mkdtempSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,dirname} from 'node:path';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
const [source,dependencyRoot]=process.argv.slice(2);
const require=createRequire(join(dependencyRoot,'package.json'));
const testModule=require.resolve('@playwright/test');
const cli=join(dirname(require.resolve('playwright')),'cli.js');
const evidence=readFileSync(join(source,'nix/ci-renderer.sh'),'utf8').match(/^mkdir -p (.+)$/m)?.[1];
if(!evidence||evidence.startsWith('/')||evidence.includes('..'))throw Error('Expected bounded relative evidence path');
const root=mkdtempSync(join(tmpdir(),'cluster-renderer-retention-'));
const old=join(root,'test-results/nix-renderer/sentinel.txt'),protectedFile=join(root,evidence,'sentinel.txt');
mkdirSync(dirname(old),{recursive:true});mkdirSync(dirname(protectedFile),{recursive:true});
writeFileSync(old,'old output');writeFileSync(protectedFile,'unchanged loader diagnostic bytes');
writeFileSync(join(root,'retention.spec.cjs'),`const {test,expect}=require(${JSON.stringify(testModule)});const {existsSync,readFileSync}=require('node:fs');test('Playwright clears its output and retains renderer evidence',()=>{expect(existsSync(${JSON.stringify(old)})).toBe(false);expect(readFileSync(${JSON.stringify(protectedFile)},'utf8')).toBe('unchanged loader diagnostic bytes');});`);
const config=join(root,'playwright.config.cjs');writeFileSync(config,`module.exports={testDir:${JSON.stringify(root)},outputDir:${JSON.stringify(join(root,'test-results'))},workers:1,retries:0,timeout:10000,reporter:'list'};`);
console.log(JSON.stringify({root,evidence,playwright:require('playwright/package.json').version,browserLaunched:false}));
execFileSync('node',[cli,'test','--config',config],{stdio:'inherit'});
if(!existsSync(protectedFile))throw Error('Evidence missing after runner completion');
